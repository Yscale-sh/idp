// Command surrogate-probe runs the synthetic compatibility surrogate and prints
// a CompatibilityEvidence file for `idpctl plan --compat-evidence`.
//
// It runs a Go stand-in for the previous reader over a synthetic fixture, not
// the previous container image; the record says so (reader:
// synthetic-surrogate). The exit code in the record comes from that run.
//
//	go run ./internal/compat/surrogate/cmd/surrogate-probe \
//	  --app carshowdb --component api --candidate <image> \
//	  --fixture internal/compat/surrogate/testdata/listings-v41.json \
//	  --migration internal/compat/surrogate/testdata/0043_drop_listings_legacy_id.json
package main

import (
	"flag"
	"fmt"
	"os"

	"github.com/yscale-sh/idp/internal/compat/surrogate"
	"sigs.k8s.io/yaml"
)

func main() {
	var req surrogate.Request
	flag.StringVar(&req.App, "app", "", "app name the record is for (required)")
	flag.StringVar(&req.Component, "component", "", "component the record is for")
	flag.StringVar(&req.Candidate, "candidate", "", "candidate image that ships the migration; must equal plan's --image (required)")
	flag.StringVar(&req.FixturePath, "fixture", "", "synthetic fixture JSON (required)")
	flag.StringVar(&req.MigrationPath, "migration", "", "migration JSON (required)")
	flag.StringVar(&req.RestorePath, "restore-path", "", "operator restore path to record")
	flag.Parse()
	if req.App == "" || req.Candidate == "" || req.FixturePath == "" || req.MigrationPath == "" {
		fmt.Fprintln(os.Stderr, "surrogate-probe: --app, --candidate, --fixture, and --migration are required")
		os.Exit(2)
	}
	out, err := yaml.Marshal(surrogate.Evidence(req))
	if err != nil {
		fmt.Fprintln(os.Stderr, "surrogate-probe:", err)
		os.Exit(1)
	}
	fmt.Print("# Generated by surrogate-probe: a synthetic surrogate reader, not the previous image.\n")
	os.Stdout.Write(out)
}
